// Анимация осей вариативного шрифта с «квантованием».
// Каждое новое сочетание веса/ширины заставляет браузер создать новый экземпляр шрифта — это дорого.
// Округляя значения (вес шагом 50, ширина шагом 5), мы переиспользуем уже созданные экземпляры:
// глазу шаги незаметны, а нагрузка на процессор падает в разы.
export const STEP = { '--w': 50, '--s': 5, '--wdth': 5 };

/** Модификаторы GSAP, округляющие CSS-переменные осей */
export function quantize(props) {
  const mods = {};
  Object.keys(props).forEach((k) => {
    if (STEP[k]) mods[k] = (v) => Math.round(parseFloat(v) / STEP[k]) * STEP[k];
  });
  return mods;
}
